function emojiFor(name, category) {
  const text = String(name || "");
  for (const [re, emoji] of EMOJI_RULES) if (re.test(text)) return emoji;
  return CATEGORY_EMOJI[category] && category !== "全部" ? CATEGORY_EMOJI[category] : "🍽️";
}
/** 模型给的图标：只收一个非 ASCII 的短字符串，别的都不要 */
function cleanEmoji(value) {
  const text = String(value || "").trim();
  return /^[^\x00-\x7f]{1,8}$/.test(text) && !/[一-鿿]/.test(text) ? text : "";
}

