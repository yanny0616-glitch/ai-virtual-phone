function normalizeShop(raw, source) {
  const category = CATEGORIES.includes(raw.category) && raw.category !== "全部" ? raw.category : "快餐简餐";
  const dishes = (raw.dishes || raw.d || []).map(d => Array.isArray(d)
    ? { name: String(d[0] || "").trim(), price: Number(d[1]) || 0, desc: String(d[2] || ""), tag: String(d[3] || ""), emoji: d[4] }
    : { name: String(d.name || "").trim(), price: Number(d.price) || 0, desc: String(d.desc || d.description || ""), tag: String(d.tag || ""), emoji: d.emoji })
    .filter(d => d.name && d.price > 0).slice(0, 14)
    .map(d => ({ ...d, emoji: cleanEmoji(d.emoji) || emojiFor(d.name, category) }));
  return {
    id: String(raw.id || ""), name: String(raw.name || "").trim().slice(0, 30), category,
    emoji: cleanEmoji(raw.emoji) || (dishes[0] && dishes[0].emoji) || CATEGORY_EMOJI[category],
    tagline: String(raw.tagline || "").slice(0, 60), rating: clamp(Number(raw.rating) || 4.6, 3.5, 5),
    minOrder: clamp(Number(raw.minOrder) || 15, 0, 80), fee: clamp(Number(raw.fee) || 3, 0, 15), factor: clamp(Number(raw.factor) || 1, 0.7, 1.5),
    off: Array.isArray(raw.off) && raw.off.length === 2 && Number(raw.off[1]) > 0 ? [Number(raw.off[0]) || 0, Number(raw.off[1])] : null,
    color: /^#[0-9a-f]{6}$/i.test(raw.color || "") ? raw.color : "#f0703a",
    dishes, source: source || raw.source || "seed", query: String(raw.query || ""), hidden: raw.hidden === true,
  };
}
